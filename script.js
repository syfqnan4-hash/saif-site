const canvas = document.getElementById("bg");
const ctx = canvas.getContext("2d");
let W, H, particles = [];
const mouse = { x: null, y: null, radius: 160 };

function Particle() {
  this.x = Math.random() * W;
  this.y = Math.random() * H;
  this.vx = (Math.random() - 0.5) * 0.6;
  this.vy = (Math.random() - 0.5) * 0.6;
  this.r = Math.random() * 2 + 1;
}
Particle.prototype.update = function () {
  this.x += this.vx;
  this.y += this.vy;
  if (this.x < 0 || this.x > W) this.vx *= -1;
  if (this.y < 0 || this.y > H) this.vy *= -1;

  if (mouse.x !== null) {
    const dx = this.x - mouse.x;
    const dy = this.y - mouse.y;
    const dist = Math.hypot(dx, dy) || 1;
    if (dist < mouse.radius) {
      const force = (mouse.radius - dist) / mouse.radius;
      this.x += (dx / dist) * force * 4;
      this.y += (dy / dist) * force * 4;
    }
  }
};
Particle.prototype.draw = function () {
  ctx.beginPath();
  ctx.arc(this.x, this.y, this.r, 0, Math.PI * 2);
  ctx.fillStyle = particleColor;
  ctx.fill();
};

function resize() {
  W = canvas.width = window.innerWidth;
  H = canvas.height = window.innerHeight;
  const count = Math.min(120, Math.floor((W * H) / 14000));
  particles = [];
  for (let i = 0; i < count; i++) particles.push(new Particle());
}

function connect() {
  for (let a = 0; a < particles.length; a++) {
    for (let b = a + 1; b < particles.length; b++) {
      const d = Math.hypot(particles[a].x - particles[b].x, particles[a].y - particles[b].y);
      if (d < 120) {
        ctx.strokeStyle = "rgba(" + lineBase + ", " + (1 - d / 120) + ")";
        ctx.lineWidth = 0.8;
        ctx.beginPath();
        ctx.moveTo(particles[a].x, particles[a].y);
        ctx.lineTo(particles[b].x, particles[b].y);
        ctx.stroke();
      }
    }
    if (mouse.x !== null) {
      const d2 = Math.hypot(particles[a].x - mouse.x, particles[a].y - mouse.y);
      if (d2 < mouse.radius) {
        ctx.strokeStyle = "rgba(6, 182, 212, " + (1 - d2 / mouse.radius) + ")";
        ctx.beginPath();
        ctx.moveTo(particles[a].x, particles[a].y);
        ctx.lineTo(mouse.x, mouse.y);
        ctx.stroke();
      }
    }
  }
}

function animate() {
  ctx.clearRect(0, 0, W, H);
  particles.forEach(function (p) { p.update(); p.draw(); });
  connect();
  requestAnimationFrame(animate);
}
window.addEventListener("resize", resize);

