const orbs = [".orb1", ".orb2", ".orb3"].map(function (s) { return document.querySelector(s); });
let rx = 0, ry = 0, mx = 0, my = 0;

window.addEventListener("pointermove", function (e) {
  mx = e.clientX;
  my = e.clientY;
  mouse.x = mx;
  mouse.y = my;
  dot.style.left = mx + "px";
  dot.style.top = my + "px";

  const px = (mx / window.innerWidth - 0.5) * 40;
  const py = (my / window.innerHeight - 0.5) * 40;
  orbs[0].style.transform = "translate(" + px + "px, " + py + "px)";
  orbs[1].style.transform = "translate(" + (-px) + "px, " + (-py) + "px)";
  orbs[2].style.transform = "translate(" + py + "px, " + (-px) + "px)";

  const ay = (mx / window.innerWidth - 0.5) * 30;
  const ax = (my / window.innerHeight - 0.5) * -30;
  avatar.style.transform = "perspective(700px) rotateX(" + ax + "deg) rotateY(" + ay + "deg)";
});
document.addEventListener("mouseleave", function () {
  mouse.x = null;
  mouse.y = null;
  avatar.style.transform = "perspective(700px) rotateX(0) rotateY(0)";
});

(function followRing() {
  rx += (mx - rx) * 0.15;
  ry += (my - ry) * 0.15;
  ring.style.left = rx + "px";
  ring.style.top = ry + "px";
  requestAnimationFrame(followRing);
})();

